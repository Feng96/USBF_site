/* Real worker, PyArrow Parquet bytes, vendored hyparquet/WKB/ZSTD; no browser. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {Worker} from 'node:worker_threads';

const project=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const fixtures=process.argv[2]||process.env.USBF_ANALYSIS_FIXTURES;
if(!fixtures)throw Error('Provide the Lustre fixture directory generated by tools/usbf-analysis-fixtures.py.');
const directory=fs.realpathSync(fixtures),index=JSON.parse(fs.readFileSync(path.join(directory,'fixtures.json'),'utf8'));
const tile=index.tile,file=path.join(directory,tile.path),source=fs.readFileSync(file),checks=[];
const ok=(condition,message)=>{assert(condition,message);checks.push(message);console.log('PASS',message);};
const same=(actual,expected,message)=>{assert.deepEqual(actual,expected,message);checks.push(message);console.log('PASS',message);};
const expectedURL='https://data.source.coop/opengeos/us-buildings/USBF_v1/'+encodeURIComponent(tile.path)+'?v='+tile.sha256;
assert.equal(createHash('sha256').update(source).digest('hex'),tile.sha256,'Fixture SHA256 must match its actual file.');
assert.equal(source.byteLength,tile.bytes);assert(index.rowGroups>=2&&index.near.features.length&&index.far.features.length,'Use the spatially separated multi-row-group fixture.');

const bootstrap=String.raw`
import {parentPort,workerData} from 'node:worker_threads';
import fs from 'node:fs';
const bytes=fs.readFileSync(workerData.file),held=new Map();
let etag='"qa-release-a"',holdNext=false,fetchSequence=0;
globalThis.self=globalThis;
globalThis.postMessage=message=>parentPort.postMessage(message);
globalThis.fetch=async(raw,options={})=>{
  const url=String(raw),range=new Headers(options.headers).get('range');
  if(url!==workerData.expectedURL||options.credentials!=='omit')throw Error('Unexpected fixture network request.');
  const match=/^bytes=(\d+)-(\d+)$/.exec(range||'');
  if(!match)throw Error('The real worker did not request an explicit HTTP byte range.');
  const start=Number(match[1]),end=Number(match[2])+1;
  if(start<0||end>bytes.byteLength||end<=start)throw Error('Invalid fixture range.');
  if(options.signal?.aborted)throw new DOMException('Fixture request cancelled.','AbortError');
  const fetchId=++fetchSequence,tag=etag;
  parentPort.postMessage({qa:'fetch',fetchId,start,end,etag:tag});
  if(holdNext){
    holdNext=false;
    // Deliberately fulfill after cancellation to test the worker's own guard.
    await new Promise(resolve=>{held.set(fetchId,resolve);parentPort.postMessage({qa:'held',fetchId,start,end});});
  }
  return new Response(bytes.subarray(start,end),{status:206,headers:{'content-type':'application/vnd.apache.parquet','content-range':'bytes '+start+'-'+(end-1)+'/'+bytes.byteLength,'content-length':String(end-start),etag:tag}});
};
await import(workerData.workerURL);
parentPort.on('message',async message=>{
  if(message.qaControl){
    try{
      if(message.action==='hold-next')holdNext=true;
      else if(message.action==='release'){for(const resolve of held.values())resolve();held.clear();}
      else if(message.action==='etag')etag=message.value;
      else if(message.action==='clear-cache')await self.onmessage({data:{type:'clear-cache'}});
      else throw Error('Unknown QA control.');
      parentPort.postMessage({qa:'ack',controlId:message.controlId});
    }catch(error){parentPort.postMessage({qa:'ack',controlId:message.controlId,error:error.message});}
    return;
  }
  self.onmessage({data:message});
});
parentPort.postMessage({qa:'ready'});
`;

class Harness{
  constructor(){
    this.messages=[];this.waiters=[];this.sequence=0;this.worker=new Worker(new URL('data:text/javascript,'+encodeURIComponent(bootstrap)),{workerData:{file,expectedURL,workerURL:pathToFileURL(path.join(project,'usbf-analysis-worker.js')).href}});
    this.worker.on('message',message=>{this.messages.push(message);for(const waiter of [...this.waiters])if(waiter.match(message)){clearTimeout(waiter.timer);this.waiters.splice(this.waiters.indexOf(waiter),1);waiter.resolve(message);}});
    this.worker.on('error',error=>{for(const waiter of this.waiters){clearTimeout(waiter.timer);waiter.reject(error);}this.waiters=[];this.error=error;});
    this.worker.on('exit',code=>{if(code!==0&&!this.closing)this.error=Error('QA worker exited with '+code);});
  }
  wait(match,{past=false}={}){
    if(this.error)return Promise.reject(this.error);
    if(past){const found=this.messages.find(match);if(found)return Promise.resolve(found);}
    return new Promise((resolve,reject)=>{const waiter={match,resolve,reject,timer:setTimeout(()=>{this.waiters.splice(this.waiters.indexOf(waiter),1);reject(Error('Timed out awaiting the real analysis worker.'));},15000)};this.waiters.push(waiter);});
  }
  async ready(){await this.wait(message=>message.qa==='ready',{past:true});}
  async control(action,value){const controlId=++this.sequence,waiting=this.wait(message=>message.qa==='ack'&&message.controlId===controlId);this.worker.postMessage({qaControl:true,controlId,action,value});const reply=await waiting;if(reply.error)throw Error(reply.error);}
  request(id,bounds=index.near.bounds,extra={}){const waiting=this.wait(message=>message.id===id&&!message.progress);this.worker.postMessage({id,bounds,tiles:[tile],...extra});return waiting;}
  async close(){this.closing=true;for(const waiter of this.waiters)clearTimeout(waiter.timer);this.waiters=[];await this.worker.terminate();}
}

let main,cancelled;
try{
  main=new Harness();await main.ready();
  ok(source.subarray(0,4).toString()==='PAR1'&&source.subarray(-4).toString()==='PAR1'&&index.codec.includes('ZSTD'),'The checked fixture is an actual PyArrow ZSTD Parquet file with matching native byte length and SHA256');
  const first=await main.request('original-near');
  assert(!first.error,first.error);same(first.data.features,index.near.features,'The real parser and ZSTD/WKB decoding return complete original polygons, courtyard holes, MultiPolygons and source attributes');
  ok(first.data.features.length===4&&!first.limited&&first.networkBytes>0&&first.bytes>=first.networkBytes,'An explicit neighborhood request decodes its real row group and reports bounded network bytes');
  const courtyard=first.data.features.find(f=>f.properties.usbf_id==='qa-courtyard'),zero=first.data.features.find(f=>f.properties.usbf_id==='qa-zero');
  ok(courtyard.properties.height_m===18&&courtyard.properties.height_missing===true&&courtyard.properties.modified===null&&zero.properties.modified===false&&zero.properties.height_missing===false&&zero.properties.height_m===null,'Native null and false values survive decoding, and a positive inherited height remains independent of its missing-input flag');
  ok(courtyard.properties.id==='1152921504606846977'&&courtyard.properties.footprint_license.includes('ODbL')&&courtyard.properties.height_license.includes('CC BY-NC'),'The native INT64 identifier and both component licenses retain their exact original meanings');
  ok(main.messages.some(m=>m.id==='original-near'&&m.progress?.done===1)&&main.messages.some(m=>m.qa==='fetch'&&m.end-m.start===tile.bytes),'Actual worker progress and full native footer-range fetching are observable without replacing the parser');
  const cached=await main.request('cached-near');same(cached.data.features,first.data.features,'A repeated explicit request returns the same complete original records');
  ok(cached.networkBytes===0&&cached.cacheHits>0,'Repeated original-data reads reuse cached real byte ranges without network transfer');
  const selected=await main.request('selected-original',index.near.bounds,{featureId:'qa-courtyard'});same(selected.data.features,[courtyard],'Selecting a USBF ID returns only that complete original building and its courtyard rather than a display fragment');
  const missing=await main.request('missing-selection',index.near.bounds,{featureId:'not-a-real-qa-id'});ok(!missing.error&&missing.data.features.length===0,'An unknown selected identifier cannot fall back to unrelated original buildings');

  await main.control('etag','"qa-release-b"');const beforeMismatch=main.messages.filter(m=>m.qa==='fetch').length;
  const changed=await main.request('changed-publication',index.far.bounds);
  ok(changed.code==='RELEASE_CHANGED'&&!changed.data&&main.messages.filter(m=>m.qa==='fetch').length>beforeMismatch,'A cached footer plus a newly read row group with a changed ETag rejects the whole mixed-publication result');
  const retried=await main.request('retry-new-publication',index.far.bounds);assert(!retried.error,retried.error);same(retried.data.features,index.far.features,'Retry after ETag rejection clears stale byte ranges and decodes the new publication consistently');
  ok(retried.networkBytes>0&&main.messages.some(m=>m.id==='retry-new-publication'&&m.data),'The successful retry performs fresh native range reads instead of reusing rejected publication bytes');
  const cachedNew=await main.request('cached-new-publication',index.far.bounds);ok(!cachedNew.error&&cachedNew.networkBytes===0&&cachedNew.cacheHits>0,'The replacement publication can be cached normally after a complete successful retry');

  cancelled=new Harness();await cancelled.ready();await cancelled.control('hold-next');
  const heldWaiting=cancelled.wait(message=>message.qa==='held'),cancelWork=cancelled.request('cancel-held-network');
  const held=await heldWaiting;cancelled.worker.postMessage({type:'cancel',id:'cancel-held-network'});await cancelled.control('release');const stopped=await cancelWork;
  ok(stopped.name==='AbortError'&&!stopped.data,'Cancelling a held real range response prevents a late result from becoming an analytical dataset');
  const afterCancel=await cancelled.request('after-cancel');assert(!afterCancel.error,afterCancel.error);same(afterCancel.data.features,index.near.features,'A new job after cancellation can decode the real fixture successfully');
  ok(afterCancel.cacheHits===0&&afterCancel.networkBytes>0&&cancelled.messages.filter(m=>m.qa==='fetch'&&m.start===held.start&&m.end===held.end).length===2,'Late bytes from the cancelled request are never inserted into the worker range cache');
  ok(!cancelled.messages.some(m=>m.id==='cancel-held-network'&&m.data),'A cancelled job never emits a delayed data result after a later job succeeds');
  const afterCached=await cancelled.request('cached-after-cancel');ok(afterCached.networkBytes===0&&afterCached.cacheHits>0,'Only the subsequent successful job populates reusable original-data ranges');

  const invalid=await main.request('too-many-source-tiles',index.near.bounds,{tiles:Array.from({length:10},()=>tile)});ok(invalid.error&&!invalid.data,'The actual worker rejects an oversized tile list before decoding or allocating larger inputs');
  console.log(JSON.stringify({passed:true,checks:checks.length,fixtureDirectory:directory,fixtureBytes:tile.bytes,rows:tile.rows,codec:index.codec,nearNetworkBytes:first.networkBytes,nearCacheHits:cached.cacheHits}));
}catch(error){console.error(error.stack||error);process.exitCode=1;}
finally{await Promise.all([main?.close(),cancelled?.close()]);}
