 assert(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),'Desktop has no horizontal overflow');
 assert(await page.locator('#attribute-rows tr').count()===240,'All 240 synthetic features available');
 await page.locator('[data-tool=identify]').click();
 const position=await page.evaluate(()=>{let r=portal.data.features[80].geometry.coordinates[0],p=portal.map.project([(r[0][0]+r[2][0])/2,(r[0][1]+r[2][1])/2]);return {x:p.x,y:p.y};});
 const bounds=await page.locator('#map').boundingBox();await page.mouse.click(bounds.x+position.x,bounds.y+position.y);
 await page.locator('#properties').waitFor({state:'visible'});
 assert(await page.evaluate(()=>portal.selected)==='DEMO-081','Polygon click selects corresponding feature');
 assert((await page.locator('#properties-content').textContent()).includes('generated examples'),'Selected feature is explicitly synthetic');
 await page.locator('[data-action=clear-selection]').click();
 await page.locator('#layer-original').check();
 assert(await page.evaluate(()=>portal.map.getLayoutProperty('demo-original','visibility'))==='visible','Original overlay switch works');
 await page.locator('#layer-footprints').uncheck();
 assert(await page.evaluate(()=>portal.map.getLayoutProperty('demo-fill','visibility'))==='none','Footprint visibility switch works');
 await page.locator('#layer-height').check();
 assert(await page.evaluate(()=>portal.map.getLayoutProperty('demo-fill','visibility'))==='visible','Height layer can show geometry independently');
 await page.locator('#opacity').fill('40');await page.locator('#opacity').dispatchEvent('input');
 assert(await page.evaluate(()=>portal.map.getPaintProperty('demo-fill','fill-opacity'))===.4,'Opacity slider changes map geometry');
 await page.locator('#layer-lod2').check();
 assert(await page.evaluate(()=>portal.map.getLayoutProperty('demo-coverage-line','visibility'))==='visible','LoD2 sample boundary toggles');
 await page.locator('#layer-height').uncheck();await page.locator('#layer-original').uncheck();await page.locator('#layer-lod2').uncheck();await page.locator('#layer-footprints').check();
 await page.locator('#opacity').fill('72');await page.locator('#opacity').dispatchEvent('input');
 await page.locator('[data-tool=measure]').click();
